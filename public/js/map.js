class GameMap {
  constructor() {
    this.reset();
  }

  reset() {
    this.grid = MAZE_GRID.map(row => [...row]);
    this.totalDots = 0;
    for (let r = 0; r < MAP_ROWS; r++) {
      for (let c = 0; c < MAP_COLS; c++) {
        if (this.grid[r][c] === 2 || this.grid[r][c] === 3) {
          this.totalDots++;
        }
      }
    }
  }

  isWall(col, row) {
    if (col < 0 || col >= MAP_COLS || row < 0 || row >= MAP_ROWS) return false; // allow tunnel wrap
    return this.grid[row][col] === 1;
  }

  isGhostHouseDoor(col, row) {
    if (col < 0 || col >= MAP_COLS || row < 0 || row >= MAP_ROWS) return false;
    return this.grid[row][col] === 4;
  }

  draw(ctx, pelletPulse) {
    for (let r = 0; r < MAP_ROWS; r++) {
      for (let c = 0; c < MAP_COLS; c++) {
        const tile = this.grid[r][c];
        const x = c * TILE_SIZE;
        const y = r * TILE_SIZE;

        if (tile === 1) {
          ctx.fillStyle = '#0000ff';
          ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);
        } else if (tile === 2) {
          // Dot
          ctx.fillStyle = '#ffb8ae';
          ctx.fillRect(x + 6, y + 6, 4, 4);
        } else if (tile === 3) {
          // Power Pellet
          if (pelletPulse) {
            ctx.fillStyle = '#ffb8ae';
            ctx.beginPath();
            ctx.arc(x + 8, y + 8, 6, 0, Math.PI * 2);
            ctx.fill();
          }
        } else if (tile === 4) {
          // Ghost house door
          ctx.fillStyle = '#ffb8ff';
          ctx.fillRect(x, y + 6, TILE_SIZE, 4);
        }
      }
    }
  }
}
